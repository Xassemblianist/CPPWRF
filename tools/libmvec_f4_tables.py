"""Tables of glibc 2.41 libmvec's 4-lane SSE4 float expf / logf / powf as a C++ header.

  python3 tools/libmvec_f4_tables.py GLIBC-2.41-SOURCE > src/core/libmvec_f4_tables.hpp

WRF's real*4 gfortran build calls _ZGVbN4v_expf, _ZGVbN4v_logf and _ZGVbN4vv_powf in vectorised loops; on any CPU
with SSE4.1 glibc selects their SSE4 variants (sysdeps/x86_64/fpu/multiarch/svml_s_{exp,log,pow}f4_core_sse4.S),
which src/core/libmvec_f4.hpp re-implements. The data are copied bit for bit from svml_s_expf_data.S,
svml_s_logf_data.S and svml_s_powf_data.S. powf's 9-bit -log(Rcp) table (_Log_LA_table) is the one of the double
log (svml_d_log_data.S, mvec_tables::kLogLA; checked equal here) and its reciprocal is Intel's rcpps as there
(mvec::detail::kRcp), so only the exp2 table __dbT and the constants are written.
"""
import re
import sys


def quads(text, start, n):
    i = text.index(start)
    q = re.findall(r"\.quad\s+(0x[0-9a-fA-F]+)", text[i:])[:n]
    assert len(q) == n
    return [int(x, 16) for x in q]


def vec(text, kind, name):
    return int(re.search(rf"{kind}_vector {name} (0x[0-9a-fA-F]+)", text).group(1), 16)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    fpu = f"{sys.argv[1]}/sysdeps/x86_64/fpu"
    exp_t = open(f"{fpu}/svml_s_expf_data.S").read()
    log_t = open(f"{fpu}/svml_s_logf_data.S").read()
    pow_t = open(f"{fpu}/svml_s_powf_data.S").read()
    dlog_t = open(f"{fpu}/svml_d_log_data.S").read()
    if quads(pow_t, "!= _Log_LA_table", 513) != quads(dlog_t, "!= _Log_LA_table", 513):
        sys.exit("powf's _Log_LA_table differs from the double log's")
    dbt = quads(pow_t, "!= __dbT", 2048)
    out = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "#pragma once",
        "// GENERATED by tools/libmvec_f4_tables.py from glibc 2.41's sources; do not edit.",
        "// glibc: sysdeps/x86_64/fpu/svml_s_expf_data.S, svml_s_logf_data.S, svml_s_powf_data.S. IEEE bit patterns.",
        "#include <cstdint>",
        "",
        "namespace cppwrf::mvec_tables {",
        "",
        "// _ZGVbN4v_expf_sse4 (__svml_sexp_data)",
    ]
    for n in ("__sInvLn2", "__sShifter", "__sLn2hi", "__sLn2lo", "__iBias", "__sPC0", "__sPC1", "__sPC2", "__sPC3",
              "__sPC4", "__sPC5", "__iAbsMask", "__iDomainRange"):
        out.append(f"inline constexpr std::uint32_t kExpf_{n.lstrip('_')} = 0x{vec(exp_t, 'float', n):08x}u;")
    out += ["", "// _ZGVbN4v_logf_sse4 (__svml_slog_data)"]
    for n in ("_sPoly_1", "_sPoly_2", "_sPoly_3", "_sPoly_4", "_sPoly_5", "_sPoly_6", "_sPoly_7", "_iHiDelta",
              "_iLoRange", "_iBrkValue", "_iOffExpoMask", "_sOne", "_sLn2"):
        out.append(f"inline constexpr std::uint32_t kLogf_{n.lstrip('_')} = 0x{vec(log_t, 'float', n):08x}u;")
    out += ["", "// _ZGVbN4vv_powf_sse4 (__svml_spow_data)"]
    for n in ("_NMINNORM", "_NMAXVAL", "_INF", "_ABSMASK", "__iAbsMask", "__iDomainRange"):
        out.append(f"inline constexpr std::uint32_t kPowf_{n.lstrip('_')} = 0x{vec(pow_t, 'float', n):08x}u;")
    for n in ("_poly_coeff_3", "_poly_coeff_4", "_ExpMask", "_Two10", "_One", "_Threshold", "_Bias", "_Bias1", "_L2",
              "__dbInvLn2", "__dbShifter", "__dbHALF", "__dbC1", "__lbLOWKBITS"):
        out.append(f"inline constexpr std::uint64_t kPowf_{n.lstrip('_')} = 0x{vec(pow_t, 'double', n):016x}ull;")
    out += ["", "// __dbT: 2^(j/2048), j = 0 ... 2047 (as stored)",
            f"inline constexpr std::uint64_t kPowfT[{len(dbt)}] = {{"]
    for i in range(0, len(dbt), 4):
        out.append("    " + ", ".join(f"0x{v:016x}ull" for v in dbt[i:i + 4]) + ",")
    out += ["};", "", "}  // namespace cppwrf::mvec_tables", ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
