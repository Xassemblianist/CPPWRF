"""The option tables of docs/MIGRATING_FROM_WRF.md, generated from tools/wrf2cppwrf.py's own tables (what the
translator accepts is what the document says, so it cannot go stale).

  gen_option_docs.py            rewrite the generated block of docs/MIGRATING_FROM_WRF.md
  gen_option_docs.py --check    exit 1 when the document's block differs from the tables (ctest docs_options_current)
  gen_option_docs.py --print    print the block
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import wrf2cppwrf as t  # noqa: E402

DOC = os.path.join(HERE, "..", "docs", "MIGRATING_FROM_WRF.md")
BEGIN = "<!-- BEGIN generated by tools/gen_option_docs.py: do not edit by hand -->"
END = "<!-- END generated -->"


def fortran(v):
    if isinstance(v, bool):
        return ".true." if v else ".false."
    return str(v)


def block() -> str:
    out = ["### Physics and dynamics schemes", "",
           "Each option accepts these values; any other value stops `cppwrf-wrf` (and the translator) at start-up.", "",
           "| Option | Values CPPWRF runs |", "|---|---|"]
    # the translator's names of the advection orders: WRF's h_mom_adv_order / v_mom_adv_order (the scalar orders go
    # with them)
    names = {"h_adv_order": "h_mom_adv_order`, `h_sca_adv_order", "v_adv_order": "v_mom_adv_order`, `v_sca_adv_order"}
    for opt, vals in t.SUPPORTED_OPTIONS.items():
        out.append(f"| `{names.get(opt, opt)}` | " + "; ".join(f"{k}: {v}" for k, v in vals.items()) + " |")
    out += ["", "Options a nest may set differently from its parent: "
            + ", ".join(f"`{k}`" for k in sorted(t.PER_DOMAIN_PHYS)) + ".", "",
            "### physics_suite", "", "| Suite | Options it sets (the `-1` entries) |", "|---|---|"]
    for s, opts in t.PHYSICS_SUITES.items():
        out.append(f"| `{s.upper()}` | " + ", ".join(f"{k} = {v}" for k, v in opts.items()) + " |")
    out += ["", "### Noah-MP options (`sf_surface_physics = 4`)", "", "| Option | Values CPPWRF runs |", "|---|---|"]
    for k, vals in t.SUPPORTED_NOAHMP_OPTIONS.items():
        out.append(f"| `{k}` | {', '.join(str(v) for v in vals)} |")
    out += ["", "### Options that must keep WRF's default", "",
            "CPPWRF runs these features only at WRF's default value (another value is an error).", "",
            "| Option | WRF default | Feature without a port |", "|---|---|---|"]
    for (grp, k), (dv, what) in t.DEFAULT_ONLY_OPTIONS.items():
        out.append(f"| `&{grp}.{k}` | `{fortran(dv)}` | {what} |")
    out += ["", "### Switches without a port (must be off)", "", "| Option | Feature |", "|---|---|"]
    for k, what in {**t.UNSUPPORTED_PHYSICS_SWITCHES, **t.UNSUPPORTED_DYNAMICS_SWITCHES}.items():
        out.append(f"| `{k}` | {what} |")
    out += ["", "### Options that change nothing in a CPPWRF run", "",
            "WRF reads them but they do not change the run here (WPS / real.exe options, infrastructure, or options "
            "of features that are off); `cppwrf-check` lists them as ignored or ported with the reason.", "",
            "| Option | Why |", "|---|---|"]
    for k, why in sorted({**t.IGNORED_WRF_OPTIONS, **t.NO_EFFECT_OPTIONS}.items()):
        out.append(f"| `{k}` | {why} |")
    out += ["", f"Every other option of WRF 4.8.0's namelist ({len(t.WRF_NAMELIST_OPTIONS)} options in all) is an "
            "error when it is away from its Registry default and CPPWRF has no port of it; an option that is not "
            "in WRF 4.8.0 is an error as in wrf.exe."]
    return "\n".join([BEGIN, ""] + out + ["", END])


def main():
    new = block()
    if "--print" in sys.argv:
        print(new)
        return 0
    with open(DOC, encoding="utf-8") as f:
        doc = f.read()
    a, b = doc.find(BEGIN), doc.find(END)
    if a < 0 or b < 0:
        sys.stderr.write(f"{DOC}: no generated block ({BEGIN} ... {END})\n")
        return 2
    cur = doc[a:b + len(END)]
    if "--check" in sys.argv:
        if cur != new:
            sys.stderr.write("docs/MIGRATING_FROM_WRF.md's option tables are out of date: run tools/gen_option_docs.py\n")
            return 1
        print("docs/MIGRATING_FROM_WRF.md: option tables current")
        return 0
    with open(DOC, "w", encoding="utf-8") as f:
        f.write(doc[:a] + new + doc[b + len(END):])
    return 0


if __name__ == "__main__":
    sys.exit(main())
